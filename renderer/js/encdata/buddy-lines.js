/** 取当前时段 key（与设计方案第 6 节矩阵一致） */
export function phaseOf(now, cfg) {
  const d = now.getDay();
  if (d === 0 || d === 6) return 'weekend';
  const mins = now.getHours() * 60 + now.getMinutes();
  const toMin = (v) => {
    const m = /^(\d{1,2}):(\d{2})$/.exec(String(v || ''));
    return m ? Number(m[1]) * 60 + Number(m[2]) : null;
  };
  const s = toMin(cfg && cfg.start) ?? 540;
  const e = toMin(cfg && cfg.end) ?? 1080;
  if (mins < s) return 'before';
  if (mins >= e) return 'after';
  const span = e - s;
  const ratio = span > 0 ? (mins - s) / span : 0;
  if (ratio >= 0.75) return 'nearEnd';
  if (ratio >= 0.45) return 'afternoon';
  // 午休：以 12:00–13:00 的视觉暂停近似，不新增配置（P2 才做精确区间）
  if (mins >= 720 && mins < 780 && s < 780 && e > 720) return 'noon';
  return 'morning';
}

/** 台词按「日期 + 时段」确定性取值，不是每次打开都随机，避免刷屏感 */
export function pickLine(list, seed) {
  if (!Array.isArray(list) || !list.length) return '';
  let h = 2166136261;
  const s = String(seed || '');
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return list[(h >>> 0) % list.length];
}
