// 换仓库时要同时改 package.json，否则应用会查到旧仓库的 Release。
const remote = execSync('git config --get remote.origin.url', { cwd: REPO_ROOT })
  .toString().trim();
const m = remote.match(/gitee\.com[:/](.+?)(?:\.git)?$/i);
if (!m) {
  console.error(`无法从 remote 解析 Gitee 仓库：${remote}`);
  process.exit(1);
}
