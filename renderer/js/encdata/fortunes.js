/** 稳定的字符串 hash（FNV-1a 变体），只用于按本地日期取签，不用于安全场景 */
export function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 按本地日期确定性取签：同一天永远同一支，跨自然日自动换新 */
export function fortuneFor(dateStr) {
  return FORTUNES[hashStr(String(dateStr || '')) % FORTUNES.length];
}
